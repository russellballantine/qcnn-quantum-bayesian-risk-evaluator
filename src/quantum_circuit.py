import os
import sys
import numpy as np
import pandas as pd
import pennylane as qml

class QuantumRiskCircuit:
    def __init__(self, mode="development"):
        """Initializes the PennyLane simulator register topology based on ontology data."""
        self.mode = mode.lower()
        self.root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        
        v_path = os.path.join(self.root_dir, "data", "VERTICES.csv")
        a_path = os.path.join(self.root_dir, "data", "ARCS.csv")
        
        if not os.path.exists(v_path) or not os.path.exists(a_path):
            raise FileNotFoundError("Ontology data cache missing. Please run src/ontology_processor.py first.")
            
        # Ingest fresh dataframes generated by Vector C
        self.vertices_df = pd.read_csv(v_path)
        self.arcs_df = pd.read_csv(a_path)
        
        # Configure simulation size
        self.total_hardware_wires = len(self.vertices_df)
        print(f"[*] Ingesting {self.total_hardware_wires} Ontological Qubit Register Definitions...")
        
        if self.mode == "development":
            # Isolate an instant, local track to run calculations safely on a laptop
            self.active_nodes = ["WebServer", "CVE-2002-0392", "BehindNetworkFirewall"]
            self.sub_df = self.vertices_df[self.vertices_df["VertexID"].isin(self.active_nodes)].copy()
            # Remap wires to local register space (0, 1, 2)
            self.sub_df["LocalWire"] = range(len(self.sub_df))
            self.wire_count = len(self.sub_df)
            self.wire_mapping = dict(zip(self.sub_df["VertexID"], self.sub_df["LocalWire"]))
            print(f"[*] Dev Mode Active: Running lightweight local simulation on [{self.wire_count}] wires.")
        else:
            # Scale compute targets up to the full 37-qubit register
            self.wire_count = self.total_hardware_wires
            self.wire_mapping = dict(zip(self.vertices_df["VertexID"], self.vertices_df["QubitWire"]))
            print(f"[!] Production Mode Active: Scale target initialized at [{self.wire_count}] wires.")

        # Initialize the PennyLane simulator backend device
        self.dev = qml.device("default.qubit", wires=self.wire_count)

    def calculate_theta(self, base_score: float) -> float:
        """Translates CVSS base score into a parameterized rotation angle."""
        # Normalize CVSS score 0-10 into a raw probability bound P (0.0 to 1.0)
        p = base_score / 10.0
        # Protect mathematical domain limits for sqrt calculations
        p = max(0.001, min(0.999, p))
        # Apply standard classical probability rotation formula
        theta = 2 * np.arcsin(np.sqrt(p))
        return theta

    def build_qbn_loader(self):
        """Constructs the variational circuit blocks mapped natively to ontology properties."""
        
        # 1. State Preparation: Load Prior Probability Rotations
        print("    -> Constructing QBN prior state loading operations...")
        df_target = self.sub_df if self.mode == "development" else self.vertices_df
        
        for _, row in df_target.iterrows():
            node_id = row["VertexID"]
            wire_idx = self.wire_mapping[node_id]
            base_score = row["BaseScoreValue"]
            
            theta = self.calculate_theta(base_score)
            # Apply individual prior rotation gate on the target wire
            qml.RY(theta, wires=wire_idx)
            
        # 2. Topology Construction: Map Relational Dependency Arcs
        print("    -> Wiring causal convolutional dependency links...")
        for _, row in self.arcs_df.iterrows():
            src_id = row["SourceID"]
            tgt_id = row["TargetID"]
            rel = row["Relationship"]
            
            # Verify if link elements belong inside our active compute window
            if src_id in self.wire_mapping and tgt_id in self.wire_mapping:
                src_wire = self.wire_mapping[src_id]
                tgt_wire = self.wire_mapping[tgt_id]
                
                # Use parameterized controlled rotations to represent threat propagation
                # Adjust phase angle based on whether it is a vulnerability or a countermeasure mitigation
                angle = -0.523 if rel == "hasCountermeasure" else 0.785
                qml.CRX(angle, wires=[src_wire, tgt_wire])


if __name__ == "__main__":
    print("[*] Testing PennyLane Integration Gate...")
    try:
        circuit_engine = QuantumRiskCircuit(mode="development")
        
        # Define an isolated check function wrapped by PennyLane
        @qml.qnode(circuit_engine.dev)
        def evaluation_circuit():
            circuit_engine.build_qbn_loader()
            # Measure expectation values on our primary risk calculation wire
            target_wire = circuit_engine.wire_mapping["WebServer"]
            return qml.expval(qml.PauliZ(target_wire))
            
        result = evaluation_circuit()
        print(f"[+] PennyLane Quantum Execution successful!")
        print(f"    - Target Expectation Value <Z> (WebServer Risk): {result:.6f}")
        
    except Exception as e:
        print(f"[-] Quantum Compilation Failed: {e}")
        sys.exit(1)
